// Makes BreakBoss.swiftpm/KnobTaperTables.swift: for every FX knob in every context, the stored
// value at each knob position 0%...100% so the measured effect (KnobTaperProbe) is that share of
// the knob's full effect. Run tools/knob_taper/make_tables.sh (Linux or macOS, any Swift 5.9+).
import Foundation

/// Stored values measured: fine near zero (some knobs change the most there), then every 0.25%.
let grid: [Float] = {
    var g: [Float] = [0, 0.000_25, 0.000_5, 0.000_75, 0.001, 0.0015, 0.002, 0.003, 0.004]
    var v: Float = 0.005
    while v < 0.9999 { g.append(v); v += 0.0025 }
    g.append(1)
    return g
}()

func table(_ p: KParam, _ c: KnobContext) -> (table: [Float], fullDB: Double) {
    let curve = KnobTaperProbe.Curve(p, c)
    var shares = grid.map { curve.share($0) }
    shares[0] = 0
    shares[shares.count - 1] = 1
    // never falls back (the random Texture knobs wobble a little): the most the knob has done so far
    for i in 1..<shares.count { shares[i] = max(shares[i], shares[i - 1]) }
    var t: [Float] = [0]
    for k in 1...100 {
        let want = Double(k) / 100
        var i = 1
        while i < shares.count - 1 && shares[i] < want { i += 1 }
        let a = shares[i - 1], b = shares[i]
        let f = b > a ? Float((want - a) / (b - a)) : 0
        t.append(grid[i - 1] + (grid[i] - grid[i - 1]) * f)
    }
    t[100] = 1
    // strictly rising, so a stored value has exactly one position
    for k in 1...100 where t[k] <= t[k - 1] { t[k] = t[k - 1] + 0.000_01 }
    return (t, curve.fullDB)
}

var entries: [(key: String, table: [Float])] = []
var cases: [(String, String)] = []           // (context.param, entry name)
var report: [String] = []
// measure every knob at once (one per core), then put them in order
let jobs = KnobContext.all.flatMap { c in KnobTaperProbe.params(c).map { (c, $0) } }
var results = [(table: [Float], fullDB: Double)?](repeating: nil, count: jobs.count)
let lock = NSLock()
DispatchQueue.concurrentPerform(iterations: jobs.count) { i in
    let r = table(jobs[i].1, jobs[i].0)
    lock.lock(); results[i] = r; lock.unlock()
}
for (i, (c, p)) in jobs.enumerated() {
    do {
        let (t, db) = results[i]!
        let name = "\(c.mode.assetSuffix)\(c.insert ? "Track" : "")_\(p.id)"
        // the same taper as one already made (within 0.002 everywhere): share it
        if let same = entries.first(where: { e in zip(e.table, t).allSatisfy { abs($0 - $1) < 0.002 } }) {
            cases.append(("\(c.mode.assetSuffix).\(c.insert).\(p.id)", same.key))
        } else {
            entries.append((name, t))
            cases.append(("\(c.mode.assetSuffix).\(c.insert).\(p.id)", name))
        }
        let at = { (k: Int) in String(format: "%.3f", t[k]) }
        report.append("\(c.name) \(p.name): full change \(String(format: "%.1f", db)) dB; stored at 10% \(at(10)), 25% \(at(25)), 50% \(at(50)), 75% \(at(75))")
        FileHandle.standardError.write((report.last! + "\n").data(using: .utf8)!)
    }
}

